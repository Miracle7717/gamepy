"""Мини-игра для тестов: "Прыжок через таймер".

Игрок проходит 10 ходов. Каждый ход выбирает одно из 3 действий:
1) искать предмет
2) чинить систему
3) идти вперёд

Нужно управлять ресурсами: энергия, здоровье и сокровища.
Игра заканчивается либо после 10 ходов, либо при падении здоровья до 0.
"""

from typing import List


def show_rules() -> None:
    print("\n=== ИГРА: ПОЛЁТ НА ЗВЁЗДНОМ КОРАБЛЕ ===")
    print("У вас 10 ходов, чтобы добраться до базы.")
    print("Ресурсы: энергия, здоровье, сокровища.")
    print("Каждый ход выбирайте: 1 - искать, 2 - чинить, 3 - идти вперёд")
    print("Победа: собрать 12 сокровищ и остаться живым.")
    print("Поражение: здоровье стало 0 или время закончилось.\n")


def get_choice() -> str:
    while True:
        choice = input("Ваш выбор (1/2/3): ").strip()
        if choice in {"1", "2", "3"}:
            return choice
        print("Введите 1, 2 или 3.")


def play_game() -> None:
    energy = 8
    health = 8
    treasure = 0
    max_turns = 10

    show_rules()

    for turn in range(1, max_turns + 1):
        print(f"\n--- Ход {turn}/10 ---")
        print(f"Энергия: {energy} | Здоровье: {health} | Сокровища: {treasure}")
        choice = get_choice()

        if choice == "1":
            print("Вы обыскиваете отсек и находите редкий артефакт.")
            treasure += 2
            energy -= 1
            health -= 1
        elif choice == "2":
            print("Вы чините систему жизнеобеспечения.")
            energy += 1
            health += 1
            treasure += 1
        else:
            print("Вы идёте вперёд и пересекаете опасный коридор.")
            treasure += 1
            energy -= 2
            health -= 1

        if energy < 0:
            energy = 0
        if health < 0:
            health = 0

        if energy == 0:
            print("У вас кончилась энергия. Корабль начинает терять управление.")
        if health == 0:
            print("Ваше здоровье упало до нуля. Игра окончена.")
            break

        print("Событие: вы продвигаетесь дальше по кораблю.")

        if treasure >= 12:
            print("\nВы собрали достаточно артефактов и можете вернуть их на базу!")
            print("Победа! Вы достигли цели.")
            return

    else:
        print("\nВремя закончилось. Корабль не успел достичь базы.")

    print(f"\nИтог: энергия={energy}, здоровье={health}, сокровища={treasure}")
    print("Попробуйте ещё раз и улучшите маршрут.")


if __name__ == "__main__":
    play_game()
